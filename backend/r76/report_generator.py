def _value(value: Any, default: str = "—") -> str:
    if value is None or value == "":
        return default

    if isinstance(value, Decimal):
        return str(value)

    if isinstance(value, float):
        return f"{value:g}"

    if isinstance(value, datetime):
        return value.strftime("%d-%m-%Y %H:%M")

    return str(value)


def _format_date(value: Any) -> str:
    if not value:
        return "—"

    try:
        if isinstance(value, str):
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
            return parsed.strftime("%d-%m-%Y")
        if isinstance(value, datetime):
            return value.strftime("%d-%m-%Y")
    except Exception:
        pass

    return _value(value)


def _result_status(value: Any) -> str:
    value = str(value or "MANUAL_REVIEW").upper()

    if value == "PASS":
        return "PASS"
    if value == "FAIL":
        return "FAIL"
    if value == "NOT_APPLICABLE":
        return "N/A"

    return "MANUAL REVIEW"


def _overall_result(session: dict[str, Any], results: list[dict[str, Any]]) -> str:
    session_result = str(session.get("final_result") or "").upper()

    if session_result in {
        "PASS",
        "FAIL",
        "NOT_APPLICABLE",
        "MANUAL_REVIEW",
    }:
        return _result_status(session_result)

    statuses = [
        str(item.get("result_status") or "").upper()
        for item in results
    ]

    if any(status == "FAIL" for status in statuses):
        return "FAIL"

    if any(status == "MANUAL_REVIEW" for status in statuses):
        return "MANUAL REVIEW"

    if statuses and all(status in {"PASS", "NOT_APPLICABLE"} for status in statuses):
        return "PASS"

    return "MANUAL REVIEW"


def _header_footer(canvas, doc):
    canvas.saveState()

    width, height = A4

    # Header line
    canvas.setStrokeColor(colors.HexColor("#D6B85A"))
    canvas.setLineWidth(1.2)
    canvas.line(18 * mm, height - 17 * mm, width - 18 * mm, height - 17 * mm)

    canvas.setFont("Helvetica-Bold", 8)
    canvas.setFillColor(colors.HexColor("#444444"))
    canvas.drawString(
        18 * mm,
        height - 13 * mm,
        "OIMLENSE — NAWI TEST REPORT",
    )

    canvas.setFont("Helvetica", 7)
    canvas.drawRightString(
        width - 18 * mm,
        height - 13 * mm,
        "OIML R 76",
    )

    # Footer
    canvas.setStrokeColor(colors.HexColor("#DDDDDD"))
    canvas.setLineWidth(0.5)
    canvas.line(
        18 * mm,
        14 * mm,
        width - 18 * mm,
        14 * mm,
    )

    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(colors.HexColor("#666666"))

    canvas.drawString(
        18 * mm,
        9 * mm,
        "Generated by OIMLense",
    )

    canvas.drawRightString(
        width - 18 * mm,
        9 * mm,
        f"Page {doc.page}",
    )

    canvas.restoreState()


